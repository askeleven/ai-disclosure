test('disclosure_due: what the next message must say', () => {
  const now = Date.parse('2026-10-17T12:00:00Z')
  const first = disclosureDue(RULES, NY, [{ role: 'user', text: 'hi', at: now - 1000 }], { now, business: 'Mia' })
  assert.equal(first.discloseNow, true)
  assert.match(first.suggestion ?? '', /AI/)

  const recent = [
    { role: 'ai', text: "I'm an AI companion.", at: now - 3_600_000 },
    { role: 'user', text: 'cool', at: now - 1000 },
  ]
  assert.equal(disclosureDue(RULES, NY, recent, { now }).discloseNow, false)
  assert.equal(disclosureDue(RULES, NY, recent, { now: now + 3 * 3_600_000 }).discloseNow, true, 'reminder due')

  const asked = [...recent, { role: 'user', text: 'wait are you a real person?', at: now }]
  const due = disclosureDue(RULES, NY, asked, { now })
  assert.equal(due.discloseNow, true)
  assert.equal(due.neverClaimHuman, true, 'New York has no anti-lying clause, but a lie undoes the notice')
  assert.ok(due.reasons.some((r) => /asked/.test(r.why)))
})

test('reads OpenAI, Anthropic and text transcripts', () => {
  const openai = parseConversation([
    { role: 'system', content: 'You are helpful.' },
    { role: 'user', content: 'hi' },
    { role: 'assistant', content: [{ type: 'text', text: "I'm an AI assistant." }] },
  ])
  assert.deepEqual(openai, [
    { role: 'user', text: 'hi' },
    { role: 'ai', text: "I'm an AI assistant." },
  ])
  const text = parseConversation('User: hello\nAI [2026-10-10T20:00:00Z]: Hi, I am an AI assistant.\nIt helps.\nStaff: Dana here.')
  assert.equal(text.length, 3)
  assert.equal(text[1].at, '2026-10-10T20:00:00Z')
  assert.match(text[1].text, /It helps/)
  assert.equal(text[2].role, 'staff')
  assert.equal(parseConversation({ messages: [{ role: 'user', content: 'x', created_at: 1760126400 }] })[0].at, 1760126400000, 'seconds become ms')
})
