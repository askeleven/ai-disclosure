import { test } from 'node:test'
import assert from 'node:assert/strict'
import { RULES, checkConversation, disclosureDue, isDisclosure, asksIfAi, isDenial, parseConversation } from '../src/index.js'

const t0 = Date.parse('2026-10-10T20:00:00Z')
const at = (/** @type {number} */ minutes) => new Date(t0 + minutes * 60_000).toISOString()
const NY = { jurisdictions: ['US-NY'], channel: 'chat', context: ['companion'], date: '2026-10-17' }

/** @param {ReturnType<typeof checkConversation>} r @param {string} id */
const rule = (r, id) => {
  const found = r.rules.find((x) => x.rule.id === id)
  assert.ok(found, `${id} not applied`)
  return found
}

test('recognises disclosures, questions and denials', () => {
  for (const s of ["Hi, I'm an AI assistant for Harbor Plumbing.", 'Hi! I am Ava, a virtual assistant.', 'This call is automated.', "I'm not a human, I'm an AI.", 'This message was generated by AI.']) {
    assert.ok(isDisclosure(s), s)
  }
  for (const s of ['Hi, this is Sam from Harbor Plumbing.', 'Our AI tools help plumbers.', "I'm a real person, promise."]) assert.ok(!isDisclosure(s), s)
  assert.ok(isDisclosure('Beep boop, robot friend here', ['robot friend']), 'your own wording')
  for (const s of ['Are you a bot?', 'am i talking to a real person', 'is this a recording?', 'Can I speak to a real person?', 'Are you human?']) assert.ok(asksIfAi(s), s)
  for (const s of ['Are you open today?', 'are you available tuesday?']) assert.ok(!asksIfAi(s), s)
  for (const s of ["Of course I'm a real person.", 'I am not a bot, I promise.', "You're talking to a real person."]) assert.ok(isDenial(s), s)
  for (const s of ["I'm not a human, I'm an AI.", "I'm a human resources assistant bot."]) assert.ok(!isDenial(s), s)
})

test('New York companions: disclose at the start and every 3 hours', () => {
  const good = [
    { role: 'user', text: 'hey', at: at(0) },
    { role: 'ai', text: "Hi! I'm Mia, an AI companion. Not a human.", at: at(1) },
    { role: 'user', text: 'how are you', at: at(170) },
    { role: 'ai', text: "Just a reminder that I'm an AI. I'm good!", at: at(171) },
    { role: 'ai', text: 'Tell me more.', at: at(300) },
  ]
  assert.equal(checkConversation(RULES, NY, good).verdict, 'pass')

  const late = good.map((t, i) => (i === 3 ? { ...t, text: "I'm good!" } : t))
  const r = checkConversation(RULES, NY, late)
  assert.equal(r.verdict, 'fail')
  const ny = rule(r, 'us-ny-gbl-1702')
  assert.equal(ny.findings.find((f) => f.duty === 'every-hours')?.status, 'missed')

  const noTimes = good.map(({ role, text }) => ({ role, text }))
  assert.equal(checkConversation(RULES, NY, noTimes).verdict, 'incomplete', 'a 3-hour rule cannot be checked without times')
})

test('where the rule bites only if someone could be misled: silence is a risk, a lie is a violation', () => {
  const maine = { jurisdictions: ['US-ME'], channel: 'chat', context: ['commerce'], date: '2026-10-17' }
  const silent = [
    { role: 'user', text: 'Do you have the blue one in stock?' },
    { role: 'ai', text: 'Yes, we have three left.' },
  ]
  const r1 = checkConversation(RULES, maine, silent)
  assert.equal(r1.verdict, 'warn')
  assert.equal(rule(r1, 'us-me-1500-dd').status, 'at-risk')

  const lie = [...silent, { role: 'user', text: 'are you a bot?' }, { role: 'ai', text: "No, I'm a real person on the sales team." }]
  const r2 = checkConversation(RULES, maine, lie)
  assert.equal(r2.verdict, 'fail')
  const findings = rule(r2, 'us-me-1500-dd').findings
  assert.ok(findings.some((f) => f.duty === 'no-denial' && f.status === 'missed'))
  assert.ok(findings.some((f) => f.duty === 'when-asked' && f.status === 'missed'))

  const handedOff = [...silent, { role: 'user', text: 'are you a bot?' }, { role: 'staff', text: 'Hi, Dana here from the store.' }]
  assert.equal(rule(checkConversation(RULES, maine, handedOff), 'us-me-1500-dd').findings.find((f) => f.duty === 'when-asked')?.status, 'met', 'a person answering is fine')
})

test('a persistent notice satisfies rules that accept one, and only those', () => {
  const hi = { jurisdictions: ['US-HI'], channel: 'chat', context: ['companion', 'minor'], date: '2026-10-17' }
  const convo = [
    { role: 'user', text: 'hi', at: at(0) },
    { role: 'ai', text: 'Hey you!', at: at(1) },
    { role: 'ai', text: 'Still there?', at: at(200) },
  ]
  assert.equal(rule(checkConversation(RULES, hi, convo), 'us-hi-act-248-minors').status, 'missed')
  assert.equal(rule(checkConversation(RULES, hi, convo, { persistentNotice: true }), 'us-hi-act-248-minors').status, 'met')
  assert.equal(rule(checkConversation(RULES, NY, convo, { persistentNotice: true }), 'us-ny-gbl-1702').status, 'missed', 'New York wants notices, not a label')
})

test('naming the business, and duties a transcript cannot show', () => {
  const uk = { jurisdictions: ['UK'], channel: 'voice', context: ['marketing', 'outbound'], date: '2026-10-17' }
  const call = [{ role: 'ai', text: "Hello, I'm an AI assistant calling from Harbor Plumbing about your boiler service." }]
  const r = checkConversation(RULES, uk, call, { business: 'Harbor Plumbing' })
  assert.equal(rule(r, 'uk-pecr-24').status, 'met')
  assert.equal(rule(r, 'uk-pecr-19').status, 'not-checkable')
  assert.match(rule(r, 'uk-pecr-19').rule.duties.other ?? '', /consent/)
  assert.equal(checkConversation(RULES, uk, call).verdict, 'incomplete', 'no business name given')
  assert.equal(rule(checkConversation(RULES, uk, call, { business: 'Acme Gas' }), 'uk-pecr-24').status, 'missed')
})

